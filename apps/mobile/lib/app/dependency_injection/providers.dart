/// Thrown when a provider that the bootstrap sequence must override is read
/// without an override. Failing here is better than silently constructing a
/// second, unconfigured instance.
final class MissingOverrideError extends Error {
  MissingOverrideError(this.providerName);

  final String providerName;

  @override
  String toString() => 'Provider $providerName must be overridden by the bootstrap sequence.';
}

