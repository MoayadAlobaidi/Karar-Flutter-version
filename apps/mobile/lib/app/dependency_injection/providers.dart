/// The shared HTTP client. Reading it when configuration is invalid is a
/// programming error: nothing may make a request in that state.
final Provider<Dio> dioProvider = Provider<Dio>((Ref ref) {
  final configuration = ref.watch(configurationResultProvider);
  final resolved = switch (configuration) {
    Success<AppConfiguration>(:final value) => value,
    Failed<AppConfiguration>() => throw StateError(
        'The HTTP client was requested while build configuration is invalid.',
      ),
  };
  final dio = buildDio(
    baseUrl: resolved.apiBaseUrl,
    defaultTimeouts: TimeoutProfile.standard,
  );
  ref.onDispose(dio.close);
  return dio;
});

/// The transport used by the refresh call ITSELF.
///
/// It attaches no credential and holds no refresh coordinator, which is what
/// makes a refresh loop structurally impossible rather than merely unlikely.
/// It also never retries: a refresh storm would be worse than a failed
/// refresh.
final Provider<ApiTransport> rawApiTransportProvider = Provider<ApiTransport>(
  (Ref ref) => DioApiTransport(
    dio: ref.watch(dioProvider),
    logger: ref.watch(loggerProvider),
    correlationIds: ref.watch(correlationIdGeneratorProvider),
    networkStatus: ref.watch(networkStatusProvider),
    clock: ref.watch(clockProvider),
    retryPolicy: RetryPolicy.none,
  ),
);

final Provider<TokenRefreshCoordinator> tokenRefreshCoordinatorProvider =
    Provider<TokenRefreshCoordinator>((Ref ref) {
  final sessions = ref.watch(sessionManagerProvider);
  final codec = ref.watch(sessionTokenCodecProvider);
  final rawClient = KararApiClient(ref.watch(rawApiTransportProvider));
  return TokenRefreshCoordinator(
    sessionManager: sessions,
    clock: ref.watch(clockProvider),
    logger: ref.watch(loggerProvider),
    refresh: (String refreshToken) async {
      try {
        final payload = await rawClient.identityRefresh(
          body: IdentityRefreshRequestDto(refreshToken: refreshToken),
          timeouts: TimeoutProfile.startup,
        );
        // The generated client now returns a typed DTO. `SessionTokenCodec` is
        // the one place a refresh payload is validated and mapped, including
        // the fallback session id the response does not repeat, so the DTO is
        // handed back as JSON rather than the codec being bypassed. Two
        // parsers for one payload is how the two drift apart.
        return codec.decode(
          payload.toJson(),
          fallbackSessionId: sessions.tokens?.sessionId,
        );
      } on ApiException catch (exception) {
        return Failed<SessionTokens>(exception.failure);
      }
    },
  );
});

/// The transport every feature uses.
final Provider<ApiTransport> apiTransportProvider = Provider<ApiTransport>(
  (Ref ref) => DioApiTransport(
    dio: ref.watch(dioProvider),
    logger: ref.watch(loggerProvider),
    correlationIds: ref.watch(correlationIdGeneratorProvider),
    networkStatus: ref.watch(networkStatusProvider),
    clock: ref.watch(clockProvider),
    sessionManager: ref.watch(sessionManagerProvider),
    refreshCoordinator: ref.watch(tokenRefreshCoordinatorProvider),
  ),
);

/// The generated client, bound to the authenticated transport.
final Provider<KararApiClient> apiClientProvider =
    Provider<KararApiClient>((Ref ref) => KararApiClient(ref.watch(apiTransportProvider)));

