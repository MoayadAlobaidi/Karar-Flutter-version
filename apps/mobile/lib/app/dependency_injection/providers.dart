final Provider<BootstrapGateway> bootstrapGatewayProvider = Provider<BootstrapGateway>(
  (Ref ref) => ApiBootstrapGateway(ref.watch(apiClientProvider)),
);

final Provider<StartupCoordinator> startupCoordinatorProvider =
    Provider<StartupCoordinator>((Ref ref) {
  final coordinator = StartupCoordinator(
    loadConfiguration: () => ref.read(configurationResultProvider),
    appLock: ref.watch(appLockGateProvider),
    sessionManager: ref.watch(sessionManagerProvider),
    bootstrapGateway: ref.watch(bootstrapGatewayProvider),
    logger: ref.watch(loggerProvider),
    clock: ref.watch(clockProvider),
  );
  ref.onDispose(coordinator.dispose);
  return coordinator;
});

final Provider<StartupListenable> startupListenableProvider =
    Provider<StartupListenable>((Ref ref) {
  final listenable = StartupListenable(ref.watch(startupCoordinatorProvider));
  ref.onDispose(listenable.dispose);
  return listenable;
});

final Provider<GoRouter> routerProvider = Provider<GoRouter>((Ref ref) {
  final router = buildAppRouter(
    startup: ref.watch(startupListenableProvider),
    coordinator: ref.watch(startupCoordinatorProvider),
    screenOverrides: ref.watch(startupScreenOverridesProvider),
    featureRoutes: ref.watch(featureRoutesProvider),
    homeBuilder: ref.watch(homeScreenBuilderProvider),
  );
  ref.onDispose(router.dispose);
  return router;
});

/// Whether this binary was compiled in release mode. Used by the configuration
/// loader, which is stricter about a release build than a debug one.
bool get isReleaseBuild => kReleaseMode;

/// Loads and validates the compiled configuration.
Result<AppConfiguration> loadCompiledConfiguration({bool? releaseBuild}) =>
    const ConfigurationLoader().load(
      values: CompiledConfiguration.asMap(),
      isReleaseBuild: releaseBuild ?? kReleaseMode,
    );
