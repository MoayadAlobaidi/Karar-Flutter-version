// COMPOSITION ROOT.
//
// Riverpod is the ONLY composition mechanism in this application. There is no
// service locator, no `GetIt`, no static singleton, and no global mutable
// instance. Everything is constructed here and reached through `ref`.
//
// Riverpod types must not appear in a feature's DOMAIN layer. The permitted
// shape is:
//
//     // features/<feature>/domain/…  — pure Dart, no Riverpod
//     abstract interface class ThingRepository {
//       Future<Result<Thing>> load();
//     }
//     final class LoadThing {                 // use case
//       const LoadThing(this._repository);
//       final ThingRepository _repository;
//       Future<Result<Thing>> call() => _repository.load();
//     }
//
//     // features/<feature>/presentation/…  — providers live HERE, not in domain
//     final loadThingProvider = Provider<LoadThing>(
//       (Ref ref) => LoadThing(ref.watch(thingRepositoryProvider)),
//     );
//
// Three providers are EXTENSION POINTS for feature workstreams. Override them
// in the ProviderScope; do not edit this file to add a feature:
//   * [featureRoutesProvider]        — protected routes;
//   * [startupScreenOverridesProvider] — real screens for gate states;
//   * [homeScreenBuilderProvider]    — the signed-in landing surface.
