function relTo(root, file) {
  return path.relative(root, file);
}

function rel(file) {
  return relTo(REPO_ROOT, file);
}

function mdFiles() {
  return walkFiles(REPO_ROOT, { exts: MD_EXTS });
}

/**
 * Blank out fenced code blocks and inline code spans, preserving the line
 * structure so reported line numbers match the file.
 */
function stripMarkdownCode(markdown) {
  const lines = markdown.split('\n');
  const out = [];
  let fenceLen = 0; // 0 = not in a fence
  for (const line of lines) {
    const m = line.match(/^\s*(`{3,})(.*)$/);
    if (m) {
      const ticks = m[1].length;
      if (fenceLen === 0) {
        fenceLen = ticks;
        out.push('');
        continue;
      }
      if (ticks >= fenceLen && m[2].trim() === '') {
        fenceLen = 0;
        out.push('');
        continue;
      }
      out.push('');
      continue;
    }
    if (fenceLen > 0) {
      out.push('');
      continue;
    }
    out.push(line.replace(/`[^`]*`/g, (s) => ' '.repeat(s.length)));
  }
  return out;
}

function targetExists(docFile, rawTarget) {
  let target = rawTarget.trim();
  if (target.startsWith('<') && target.endsWith('>')) target = target.slice(1, -1);
  // Drop an optional trailing markdown title: (path "Title")
  target = target.replace(/\s+["'][^"']*["']$/, '');
  const [pathPart] = target.split('#');
  const clean = pathPart.split('?')[0];
  if (clean === '') return true; // pure anchor
  let decoded = clean;
  try {
    decoded = decodeURIComponent(clean);
  } catch {
    /* keep raw */
  }
  const resolved = decoded.startsWith('/')
    ? path.join(REPO_ROOT, decoded)
    : path.resolve(path.dirname(docFile), decoded);
  return fs.existsSync(resolved);
}

function isExternal(target) {
  return /^(https?:\/\/|mailto:|tel:|data:|javascript:|#)/i.test(target.trim());
}

function checkLinks(files) {
  const problems = [];
  const linkRe = /!?\[[^\]]*\]\(([^()\s]+(?:\s+"[^"]*")?)\)/g;
  const refDefRe = /^\s*\[[^\]]+\]:\s+(\S+)/;
  for (const file of files) {
    const lines = stripMarkdownCode(readText(file));
    lines.forEach((line, i) => {
      for (const m of line.matchAll(linkRe)) {
        const target = m[1];
        if (isExternal(target)) continue;
        if (!targetExists(file, target)) {
          problems.push(`${rel(file)}:${i + 1} broken link '${target}'`);
        }
      }
      const def = line.match(refDefRe);
      if (def && !isExternal(def[1]) && !targetExists(file, def[1])) {
        problems.push(`${rel(file)}:${i + 1} broken reference definition '${def[1]}'`);
      }
    });
  }
  return problems;
}

// PHASE STATUS MUST AGREE ACROSS EVERY DOCUMENT THAT STATES IT.
//
// A commit whose entire purpose was to stop claiming Phase 4 was COMPLETE
// updated three documents and left five others saying COMPLETE — including
// `docs/roadmap.md`, the canonical phase table, and a prose block in the same
// README whose status block had just been corrected. Every individual document
// was internally coherent; nothing compared them, so nothing failed.
//
// This reads the current phase and its status from the README status block,
// then requires that no other tracked document contradicts it. It deliberately
// checks only the CURRENT phase: earlier phases are settled history and later
// ones are not claimed yet.
/**
 * Documents that contradict a fact the tree can be asked about.
 *
 * `docs:check` was green while `docs/phases/phase-05.md` said a statement could
 * not be chosen on a device — twenty lines from its own deliverables table
 * saying the picker was built — and while the architecture registry said
 * modules held no code, beside 484 module source files. A green documentation
 * gate that cannot see either of those is not a documentation gate.
 *
 * Only facts a machine can DERIVE are pinned here, and each rule names the
 * artifact it derives from. This is deliberately not a prose parser: it asks a
 * small number of yes/no questions of the source and refuses a document that
 * answers them differently.
 */
function checkDerivedFacts() {
  const problems = [];
  const read = (rel) => {
    const full = path.join(REPO_ROOT, rel);
    return fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
  };
  const countFiles = (dir, filter) => {
    const root = path.join(REPO_ROOT, dir);
    if (!fs.existsSync(root)) return 0;
    let n = 0;
    const walk = (d) => {
      for (const entry of fs.readdirSync(d, { withFileTypes: true })) {
        const full = path.join(d, entry.name);
        if (entry.isDirectory()) {
          if (EXCLUDED_DIRS.has(entry.name) || entry.name === '__tests__') continue;
          walk(full);
        } else if (filter(full)) n += 1;
      }
    };
    walk(root);
    return n;
  };

  // A. The pure-package list in the docs must match the executable checker.
  const runner = read('scripts/checks/architecture.mjs');
  if (runner === null) {
    problems.push('scripts/checks/architecture.mjs missing — the pure-package fact cannot be derived');
  } else {
    const block = /const PURE_PACKAGES = \[([\s\S]*?)\];/.exec(runner);
    if (block === null) {
      problems.push('architecture.mjs has no parseable PURE_PACKAGES — this rule is now blind');
    } else {
      const actual = [...block[1].matchAll(/'([\w-]+)'/g)].map((m) => m[1]);
      const WORDS = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight'];
      const expected = WORDS[actual.length] ?? String(actual.length);
      for (const rel of ['docs/testing/architecture-test-registry.json', 'docs/testing/architecture-tests.md']) {
        const text = read(rel);
        if (text === null) continue;
        for (const word of WORDS) {
          if (word === expected) continue;
          const stale = new RegExp(`the ${word} pure packages`, 'i');
          if (stale.test(text)) {
            problems.push(
              `${rel} says "the ${word} pure packages"; the checker declares ${actual.length} (${actual.join(', ')})`,
            );
          }
        }
      }
    }
  }

  // B. The registry must not claim modules are empty while they hold code.
  const moduleSources = countFiles('modules', (f) => f.endsWith('.ts') && !f.endsWith('.test.ts'));
  const registryText = read('docs/testing/architecture-test-registry.json');
  if (registryText !== null && moduleSources > 0) {
    for (const claim of ['no module code', 'modules have no code', 'no TypeScript in modules']) {
      if (registryText.toLowerCase().includes(claim)) {
        problems.push(
          `architecture-test-registry.json says "${claim}" while modules/ holds ${moduleSources} production files`,
        );
      }
    }
  }

  // C. The phase report must not deny a picker that is registered.
  const androidPicker = read('apps/mobile/android/app/src/main/kotlin/com/kararfinance/app/StatementDocumentPicker.kt');
  const iosPicker = read('apps/mobile/ios/Runner/StatementDocumentPicker.swift');
  // Every document a reader consults for current state, not just the phase
  // report: the contradiction recurred across four of them last time.
  const CURRENT_STATE_DOCS = [
    'docs/phases/phase-05.md',
    'README.md',
    'apps/mobile/README.md',
    'docs/roadmap.md',
    'docs/onboarding/developer.md',
    'docs/onboarding/flutter.md',
    'docs/architecture/flutter.md',
    'docs/architecture/backend.md',
    'docs/architecture/overview.md',
    'docs/phases/README.md',
  ];
  const phase = read('docs/phases/phase-05.md');
  if (androidPicker !== null && iosPicker !== null) {
    for (const rel of CURRENT_STATE_DOCS) {
      const text = read(rel);
      if (text === null) continue;
      for (const claim of [
        'no file picker adapter',
        'cannot be chosen on a device',
        'no picker adapter ships',
        'picker port with no adapter',
        // The deferred-work list said this and rules C/D did not know the
        // words. Every phrase here was found in the tree, not imagined.
        'picker port with no implementation',
        'nobody can choose a file',
      ]) {
        if (text.toLowerCase().includes(claim)) {
          problems.push(`${rel} says "${claim}" while both native picker implementations exist`);
        }
      }
    }
  }

  // D. The phase report must not deny work whose invocation is in the source.
  const manual = read('modules/transactions/application/use-cases/create-manual-transaction.ts') ?? '';
  const csv = read('modules/statement-imports/application/use-cases/commit-statement-import.ts') ?? '';
  if (phase !== null) {
    if (manual.includes('merchantRules.evaluate') && csv.includes('this.categories.match')) {
      for (const rel of CURRENT_STATE_DOCS) {
        const text = read(rel);
        if (text === null) continue;
        for (const claim of [
          'nothing applies merchant rules',
          'categorization is assignment, not a pipeline',
          'merchant rules are schema and domain; nothing applies them',
        ]) {
          if (text.toLowerCase().includes(claim)) {
            problems.push(`${rel} says "${claim}" while both write paths invoke the evaluator`);
          }
        }
      }
    }
    if (manual.includes('suggestTransfersFor') && csv.includes('suggestTransfersFor')) {
      for (const claim of ['suggestion is not', 'nothing calls it']) {
        if (phase.toLowerCase().includes(claim)) {
          problems.push(
            `docs/phases/phase-05.md says "${claim}" while both write paths trigger suggestion generation`,
          );
        }
      }
    }
  }

  // E. A module whose use cases the API app wires, and which holds production
  // code, may not have documentation saying it has neither.
  //
  // This is the shape the staleness actually took: six MODULE.md files and
  // three layer READMEs said "no transport layer exists yet" long after the
  // routes were mounted and driven by the conformance suite. Rules C and D
  // could not see it -- they match fixed phrases in a fixed file list, and
  // these were different words in different files.
  //
  // Both halves are derived per MODULE, never globally: the skeleton modules
  // say "no application code exists yet" and are telling the truth, so a rule
  // keyed on whether the FINANCIAL app has controllers would flag all of them.
  const composition = read('apps/api/src/composition/phase5-modules.ts') ?? '';
  const wired = new Set(
    [...composition.matchAll(/@karar\/([a-z-]+)/g)]
      .map((m) => m[1])
      .filter((name) => fs.existsSync(path.join(REPO_ROOT, 'modules', name))),
  );
  const TRANSPORT_DENIALS = [
    'no transport layer exists yet',
    'no transport layer and no',
    'no http surface and no controller exist',
    'no ingestion endpoint and no transport layer exist',
    'no transport exists for this module yet',
    'there is no http surface here',
    'no transport, no ingestion',
    'neither is a running path',
  ];
  const EMPTINESS_DENIALS = ['no application code exists yet', 'this directory is a skeleton'];
  for (const rel of walkFiles(path.join(REPO_ROOT, 'modules'), { exts: MD_EXTS })
    .map((f) => path.relative(REPO_ROOT, f))) {
    // modules/README.md sits directly under modules/ and names no module.
    const moduleName = rel.split(path.sep)[1];
    if (moduleName === undefined) continue;
    if (!fs.existsSync(path.join(REPO_ROOT, 'modules', moduleName, 'MODULE.md'))) continue;
    const text = read(rel);
    if (text === null) continue;
    const lower = text.toLowerCase();
    if (wired.has(moduleName)) {
      for (const denial of TRANSPORT_DENIALS) {
        if (lower.includes(denial)) {
          problems.push(
            `${rel} says "${denial}" while apps/api/src/composition/phase5-modules.ts wires @karar/${moduleName} and mounts its routes`,
          );
        }
      }
    }
    // An emptiness claim is judged against the directory the document sits in,
    // not against its module: a layer README that says "this directory is a
    // skeleton" is describing its own layer, and several modules have layers
    // that are genuinely still empty next to layers that are not.
    const ownDir = path.dirname(rel);
    const ownSourceCount = countFiles(
      ownDir,
      (f) => f.endsWith('.ts') && !f.endsWith('.test.ts'),
    );
    if (ownSourceCount > 0) {
      for (const denial of EMPTINESS_DENIALS) {
        if (lower.includes(denial)) {
          problems.push(
            `${rel} says "${denial}" while ${ownDir} holds ${ownSourceCount} production files`,
          );
        }
      }
    }
  }

  // F. No current-state document may deny a Flutter financial surface that
  // exists. Three of them did, including one that contradicted itself ten
  // lines later.
  const featuresDir = path.join(REPO_ROOT, 'apps', 'mobile', 'lib', 'features');
  const financialFeatures = fs.existsSync(featuresDir)
    ? fs
        .readdirSync(featuresDir, { withFileTypes: true })
        .filter((e) => e.isDirectory())
        .map((e) => e.name)
        .filter((n) => /^(financial_|payment_|statement_|transaction|transfer_)/.test(n))
    : [];
  if (financialFeatures.length > 0) {
    for (const rel of CURRENT_STATE_DOCS) {
      const text = read(rel);
      if (text === null) continue;
      const lower = text.toLowerCase();
      for (const claim of [
        'any flutter financial surface',
        'not built: any flutter surface',
        'no flutter financial surface',
      ]) {
        const at = lower.indexOf(claim);
        if (at < 0) continue;
        // Only a DENIAL is a problem. The same words appear in sentences that
        // describe what was built, so the preceding clause decides.
        const before = lower.slice(Math.max(0, at - 60), at);
        if (/not built|does not exist|no |never/.test(before)) {
          problems.push(
            `${rel} denies a Flutter financial surface while apps/mobile/lib/features holds ${financialFeatures.length} of them (${financialFeatures.join(', ')})`,
          );
        }
      }
    }
  }

  return problems;
}

function checkPhaseStatusConsistency(files) {
  const problems = [];
  const readmePath = path.join(REPO_ROOT, 'README.md');
  if (!fs.existsSync(readmePath)) return ['README.md missing'];
  const readme = fs.readFileSync(readmePath, 'utf8');

  const status = readme.match(/\|\s*Current phase\s*\|\s*\*\*([0-9.]+)\s*[—-]\s*([A-Z ]+?)\*\*/);
  if (!status) {
    return ['README.md has no parseable "Current phase" row; every other check here depends on it'];
  }
  const [, phase, declared] = [status[0], status[1], status[2].trim()];

  // Only a claim of completion is a contradiction. "IN PROGRESS" elsewhere is
  // agreement, and a document may legitimately not mention the phase at all.
  if (declared === 'COMPLETE') return problems;

  const claim = new RegExp(
    `Phase ${phase.replace('.', '\\.')}\\b[^.\n]{0,80}?\\b(?:is |was |—\\s*)?COMPLETE\\b` +
      `|Phase ${phase.replace('.', '\\.')}\\b[^.\n]{0,80}?\\bis complete\\b` +
      `|\\bPhase ${phase.replace('.', '\\.')} delivered\\b`,
    'i',
  );

  for (const file of files) {
    const relative = path.relative(REPO_ROOT, file);
    // Phase reports for EARLIER phases are historical records and correctly
    // describe their own phase as complete.
    if (/docs\/phases\/phase-0(?!4)/.test(relative)) continue;
    // The compliance corpus is a dated gate snapshot; it scopes its own claims.
    if (relative.startsWith('docs/compliance/')) continue;

    const text = fs.readFileSync(file, 'utf8');
    text.split('\n').forEach((line, index) => {
      // A line that states what COMPLETE would mean, or denies completion, is
      // not a claim of it.
      if (/does not mean|will mean|not complete|NOT a closeout|is NOT complete/i.test(line)) return;

      // A TABLE ROW states the phase in one cell and its status in another, so
      // no "Phase 4 ... COMPLETE" prose pattern can ever match it. That is the
      // exact shape the canonical roadmap table uses, and the exact shape that
      // survived the correction it was supposed to receive.
      const cells = line.startsWith('|') ? line.split('|').map((c) => c.trim()) : null;
      const isPhaseRow = cells !== null && cells.some((c) => c.replace(/\*/g, '').trim() === phase);
      if (isPhaseRow && /\bCOMPLETE\b/.test(line)) {
        problems.push(
          `${relative}:${index + 1} is a table row for phase ${phase} marked COMPLETE, ` +
            `but README declares it ${declared}.`,
        );
        return;
      }

      if (claim.test(line)) {
        problems.push(
          `${relative}:${index + 1} says Phase ${phase} is COMPLETE, but README declares it ${declared}. ` +
            'A status stated in more than one place has to agree in all of them.',
        );
      }
    });
  }
  return problems;
}

function checkReadmePhase(registry) {
  const problems = [];
  const readmePath = path.join(REPO_ROOT, 'README.md');
  if (!fs.existsSync(readmePath)) return ['README.md missing'];
  const row = readText(readmePath)
    .split('\n')
    .find((l) => /^\|\s*Current phase\s*\|/i.test(l));
  if (!row) {
    problems.push(`README.md: no '| Current phase |' row`);
    return problems;
  }
  const value = row.split('|')[2] ?? '';
  const num = value.match(/(\d+(?:\.\d+)?)/);
  if (!num) {
    problems.push(`README.md: 'Current phase' row carries no phase number ('${value.trim()}')`);
  } else if (Number(num[1]) !== registry.currentPhase) {
    problems.push(
      `README.md: 'Current phase' says ${num[1]} but ${REGISTRY_REL} says ${registry.currentPhase}`,
    );
  }
  return problems;
}

function phaseReportName(phase) {
  const intPart = Math.floor(phase);
  const padded = String(intPart).padStart(2, '0');
  // Fractional phases use a dash, not a dot, in the filename (the canonical
  // Phase 3.5 report is docs/phases/phase-03-5.md).
  const frac = phase === intPart ? '' : `-${String(phase).split('.')[1]}`;
  return `phase-${padded}${frac}.md`;
}

function checkPhaseReport(registry) {
  const name = phaseReportName(registry.currentPhase);
  const full = path.join(REPO_ROOT, 'docs', 'phases', name);
  return fs.existsSync(full)
    ? []
    : [`docs/phases/${name} missing for currentPhase ${registry.currentPhase}`];
}

function checkAdrReferences(files) {
  const problems = [];
  const adrDir = path.join(REPO_ROOT, 'docs', 'adr');
  const adrFiles = fs.existsSync(adrDir) ? fs.readdirSync(adrDir) : [];
  const exists = (num) => adrFiles.some((f) => f.startsWith(`${num}-`) && f.endsWith('.md'));
  const seen = new Set();
  for (const file of files) {
    const lines = stripMarkdownCode(readText(file));
    lines.forEach((line, i) => {
      const refs = [
        ...line.matchAll(/\[ADR-(\d{4})\]/g),
        ...line.matchAll(/\badr\/(\d{4})-[A-Za-z0-9-]*\.md/g),
      ];
      for (const m of refs) {
        const key = `${rel(file)}:${i + 1}:${m[1]}`;
        if (seen.has(key)) continue;
        seen.add(key);
        if (!exists(m[1])) {
          problems.push(`${rel(file)}:${i + 1} references ADR ${m[1]}, absent from docs/adr/`);
        }
      }
    });
  }
  return problems;
}

function checkModuleDocs() {
  const problems = [];
  for (const mod of childDirs(path.join(REPO_ROOT, 'modules'))) {
    if (!fs.existsSync(path.join(REPO_ROOT, 'modules', mod, 'MODULE.md'))) {
      problems.push(`modules/${mod}: MODULE.md missing`);
    }
  }
  return problems;
}

function checkMermaid(files) {
  const problems = [];
  for (const file of files) {
    const lines = readText(file).split('\n');
    let fenceLen = 0;
    let isMermaid = false;
    let block = [];
    let openLine = 0;
    lines.forEach((line, i) => {
      const m = line.match(/^\s*(`{3,})(.*)$/);
      if (m) {
        const ticks = m[1].length;
        const rest = m[2].trim();
        if (fenceLen === 0) {
          fenceLen = ticks;
          isMermaid = rest.split(/\s+/)[0] === 'mermaid';
          block = [];
          openLine = i + 1;
          return;
        }
        if (ticks >= fenceLen && rest === '') {
          if (isMermaid) {
            const content = block.filter((l) => l.trim() !== '' && !l.trim().startsWith('%%'));
            if (content.length === 0) {
              problems.push(`${rel(file)}:${openLine} empty mermaid block`);
            } else {
              const first = content[0].trim().split(/\s+/)[0];
              if (!MERMAID_TYPES.has(first)) {
                problems.push(
                  `${rel(file)}:${openLine} mermaid block starts with '${first}' — expected one of ${[...MERMAID_TYPES].join('|')}`,
                );
              }
            }
          }
          fenceLen = 0;
          isMermaid = false;
          return;
        }
        block.push(line);
        return;
      }
      if (fenceLen > 0) block.push(line);
    });
    if (fenceLen > 0) {
      problems.push(`${rel(file)}: unbalanced code fence (opened line ${openLine}, never closed)`);
    }
  }
  return problems;
}

function checkPhaseTemplate() {
  const templatePath = path.join(REPO_ROOT, 'docs', 'phases', 'PHASE_TEMPLATE.md');
  if (!fs.existsSync(templatePath)) return ['docs/phases/PHASE_TEMPLATE.md missing'];
  const content = readText(templatePath);
  const problems = [];
  for (const section of ['Evidence produced', 'SOC 2 mapping', 'ISO 27001 mapping']) {
    if (!new RegExp(`^##\\s+${section}\\s*$`, 'm').test(content)) {
      problems.push(
        `docs/phases/PHASE_TEMPLATE.md: missing '## ${section}' section (compliance-gate wiring)`,
      );
    }
  }
  return problems;
}

