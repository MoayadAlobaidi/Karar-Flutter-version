#!/usr/bin/env node
// Documentation checks — deterministic only.
//
// What this checks:
//   1. Internal markdown links: every [text](target) with a non-http target
//      must resolve to an existing file or directory relative to the doc
//      (anchors stripped). Links inside code fences and inline code are ignored.
//   2. Root README.md has a "Current phase" row matching the architecture-test
//      registry's currentPhase.
//   3. The current phase report docs/phases/phase-0N.md exists.
//   4. Every ADR referenced as [ADR-00XX] or adr/00XX-*.md in the docs exists
//      in docs/adr/.
//   5. Every direct child of modules/ has MODULE.md (shared with architecture
//      test 16; duplicated cheaply here so docs:check stands alone).
//   6. Mermaid blocks: syntactic sanity only — balanced fences, non-empty
//      blocks, first word one of the known diagram types. This deliberately
//      does NOT pretend to validate the full mermaid grammar.
//   7. docs/phases/PHASE_TEMPLATE.md carries the compliance-gate sections
//      ("Evidence produced", "SOC 2 mapping", "ISO 27001 mapping").
//   8. Emoji decoration, banned by documentation-style-guide.md §4. Detected by
//      Unicode emoji property rather than by "not ASCII", because this
//      repository documents an Arabic-first product: a not-ASCII rule would
//      flag every Arabic string, every RTL mark, and the em dashes, section
//      signs and box-drawing diagrams the house style is built on. Only
//      characters that render as colour emoji by default — or are forced to by
//      U+FE0F — are decoration. Dingbats (U+2713, U+2717) and text-presentation
//      pictographs (U+2194, U+25B6) are typography and stay legal.
//   9. AI attribution — "generated with <assistant>", "co-authored-by:
//      <assistant>" and their relatives. Style guide §4: committed documents
//      carry no tool attribution of any kind. The rule matches the attribution
//      shape, not the tool's name on its own, because branch names in this
//      repository legitimately contain one.
//  10. Generation-attribution lines — a whole line whose content is "generated
//      by/with <anything>". Tool-agnostic and line-anchored, so a sentence that
//      describes evidence "generated by the system as it runs" stays legal
//      while a trailing signature line does not.
//  11. Assistant boilerplate — "as an AI", first-person refusals, chat
//      pleasantries. A document reports; it does not converse.
//  12. Allowance liveness — every entry in STYLE_ALLOWANCES must still suppress
//      something. An allowance that has stopped matching is a hole left open
//      for the next violation, so a stale one fails the run instead of
//      lingering unnoticed.
//
// Checks 8-11 read code-stripped prose. Fenced blocks and inline code carry
// fixtures, terminal output and quoted samples, where a non-ASCII character is
// the subject rather than decoration; excluding them structurally is what makes
// the rules usable on this corpus. The cost is that they do not see inside a
// fence, which is stated here rather than discovered later.
//
// A self-test runs at the end of every invocation (or alone via --self-test):
// it seeds one violation per rule 8-12 in a temp tree, asserts each rule fires
// and names the seeded file, and asserts a set of legitimate shapes stays
// unflagged. Checks 1-7 predate it and are not covered by it.
//
// There is NO natural-language contradiction detection here — deterministic
// checks only.
//
// Zero dependencies: node: builtins only.

