/** Codepoint label for a match, e.g. "U+2705" or "U+26A0 U+FE0F". */
function codepointsOf(text) {
  return [...text]
    .map((c) => `U+${c.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')}`)
    .join(' ');
}

/**
 * True when `hit` sits inside an occurrence of an allowance's exact quote on
 * the same line of the same file. Span containment, not a line- or file-level
 * pass: a second violation elsewhere on the same line still fails.
 */
function isAllowed(allowance, relFile, checkName, line, start, end) {
  if (allowance.file !== relFile || allowance.check !== checkName) return false;
  for (let from = 0; ;) {
    const at = line.indexOf(allowance.quote, from);
    if (at === -1) return false;
    if (start >= at && end <= at + allowance.quote.length) return true;
    from = at + 1;
  }
}

/**
 * Run `rules` over the code-stripped prose of every file, dropping hits an
 * allowance covers. `describe` turns a hit into the problem line. Returns
 * { problems, usedAllowances }.
 */
function scanProse(files, root, checkName, rules, describe) {
  const problems = [];
  const used = new Set();
  for (const file of files) {
    const relFile = relTo(root, file);
    const lines = stripMarkdownCode(readText(file));
    lines.forEach((line, i) => {
      for (const { label, re } of rules) {
        for (const m of line.matchAll(re)) {
          const start = m.index;
          const end = start + m[0].length;
          const allowance = STYLE_ALLOWANCES.find((a) =>
            isAllowed(a, relFile, checkName, line, start, end),
          );
          if (allowance) {
            used.add(STYLE_ALLOWANCES.indexOf(allowance));
            continue;
          }
          problems.push(describe({ relFile, line: i + 1, label, text: m[0] }));
        }
      }
    });
  }
  return { problems, usedAllowances: used };
}

function checkEmoji(files, root) {
  return scanProse(
    files,
    root,
    'no-emoji',
    EMOJI_RULES,
    ({ relFile, line, label, text }) =>
      `${relFile}:${line} emoji ${codepointsOf(text)} (${label}) — the style guide bans emoji in documentation; a status icon becomes a word: PASS, FAIL, COMPLETE, PENDING, WARNING`,
  );
}

function checkAiAttribution(files, root) {
  return scanProse(
    files,
    root,
    'no-ai-attribution',
    AI_ATTRIBUTION_RULES,
    ({ relFile, line, label, text }) =>
      `${relFile}:${line} AI attribution '${text.trim()}' (${label}) — a committed document names the team that owns it, not the tool that touched it`,
  );
}

/**
 * Strip the markdown decoration a signature line hides behind — list markers,
 * blockquote markers, emphasis, small-text tags, horizontal-rule dashes — so
 * the anchor sees the sentence itself.
 */
function undecorate(line) {
  return line
    .replace(/<\/?(?:sub|sup|small|em|strong|i|b)>/gi, '')
    .replace(/^[\s>*_~-]+/, '')
    .replace(/[\s*_~]+$/, '')
    .trim();
}

function checkGeneratedByLine(files, root) {
  const problems = [];
  const used = new Set();
  for (const file of files) {
    const relFile = relTo(root, file);
    const lines = stripMarkdownCode(readText(file));
    lines.forEach((raw, i) => {
      const line = undecorate(raw);
      if (line === '') return;
      for (const { label, re } of GENERATED_LINE_RULES) {
        if (!re.test(line)) continue;
        // A line-level rule takes a line-level allowance: the quote must be the
        // whole undecorated line, so an allowance cannot be widened by adding
        // text around the sentence it was written for.
        const allowance = STYLE_ALLOWANCES.find(
          (a) => a.file === relFile && a.check === 'no-generated-by-line' && a.quote === line,
        );
        if (allowance) {
          used.add(STYLE_ALLOWANCES.indexOf(allowance));
          continue;
        }
        problems.push(
          `${relFile}:${i + 1} ${label} '${line}' — a document states what it is, not what produced it`,
        );
      }
    });
  }
  return { problems, usedAllowances: used };
}

function checkAssistantBoilerplate(files, root) {
  return scanProse(
    files,
    root,
    'no-assistant-boilerplate',
    BOILERPLATE_RULES,
    ({ relFile, line, label, text }) =>
      `${relFile}:${line} assistant boilerplate '${text.trim()}' (${label}) — documentation reports in the team's voice; it does not converse`,
  );
}

/**
 * Every allowance must still suppress a real hit. A suppression that no longer
 * suppresses anything has become an unexamined exemption, so it fails here
 * rather than sitting in the list until something new slips under it.
 */
function checkAllowancesLive(usedIndexes) {
  const problems = [];
  STYLE_ALLOWANCES.forEach((a, i) => {
    if (usedIndexes.has(i)) return;
    problems.push(
      `allowance ${i + 1} (${a.file}, ${a.check}, '${a.quote}') matched nothing — delete it, or restore the text it was written for`,
    );
  });
  return problems;
}

/** Run checks 8-11 over one file set and fold their allowance usage together. */
function runStyleChecks(files, root) {
  const emoji = checkEmoji(files, root);
  const attribution = checkAiAttribution(files, root);
  const generated = checkGeneratedByLine(files, root);
  const boilerplate = checkAssistantBoilerplate(files, root);
  const used = new Set([
    ...emoji.usedAllowances,
    ...attribution.usedAllowances,
    ...generated.usedAllowances,
    ...boilerplate.usedAllowances,
  ]);
  return {
    checks: [
      { name: 'no-emoji', problems: emoji.problems },
      { name: 'no-ai-attribution', problems: attribution.problems },
      { name: 'no-generated-by-line', problems: generated.problems },
      { name: 'no-assistant-boilerplate', problems: boilerplate.problems },
      { name: 'style-allowances-live', problems: checkAllowancesLive(used) },
    ],
  };
}

// ---------------------------------------------------------------------------
// Self-test: seed one violation per style rule in a temp tree and assert every
// rule fails on it and names it, and that a set of legitimate shapes stays
// unflagged. Runs at the end of every normal invocation so a passing run is
// evidence the rules can still fail.
// ---------------------------------------------------------------------------

// Written as escapes so this file stays pure ASCII: a check that forbids emoji
// in documentation has no business carrying emoji in its own source.
const SEED = {
  checkMark: '\u2705', // WHITE HEAVY CHECK MARK — colour emoji by default
  warningVs16: '\u26A0\uFE0F', // WARNING SIGN + VS16 — text symbol forced to emoji
  dingbatCheck: '\u2713', // CHECK MARK — a dingbat, legal
  dingbatX: '\u2717', // BALLOT X — a dingbat, legal
  leftRight: '\u2194', // LEFT RIGHT ARROW — pictographic, text presentation, legal
  play: '\u25B6', // BLACK RIGHT-POINTING TRIANGLE — same, legal
  emDash: '\u2014',
  middot: '\u00B7',
  rlm: '\u200F', // RIGHT-TO-LEFT MARK
  lrm: '\u200E', // LEFT-TO-RIGHT MARK
  arabic: '\u0627\u0644\u0645\u0646\u0635\u0629', // "the platform"
};

// Allowance-dependent cases read the live list, and only by the file an entry
// names — never by list position. Deleting an allowance once its reason expires
// therefore retires its cases with it rather than breaking the self-test, which
// is the point: an allowance is meant to be removable.
const ALLOWED_FILE = 'docs/legacy/qarar-audit.md';
const STALE_FILE = 'docs/legacy/security-findings.md';
const ALLOWED_ENTRY = STYLE_ALLOWANCES.find(
  (a) => a.file === ALLOWED_FILE && a.check === 'no-assistant-boilerplate',
);
const STALE_ENTRY = STYLE_ALLOWANCES.find((a) => a.file === STALE_FILE);

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');

function buildSelfTestFixture() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'karar-docs-selftest-'));
  const write = (relPath, content) => {
    const full = path.join(root, relPath);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, content);
  };

  write(
    'docs/seed-emoji.md',
    `# Seed\n\n| Check | Status |\n|---|---|\n| Links | ${SEED.checkMark} |\n`,
  );
  write('docs/seed-emoji-vs16.md', `# Seed\n\n${SEED.warningVs16} Rotation is overdue.\n`);
  write(
    'docs/seed-attribution.md',
    `# Seed\n\nThis runbook was written by Claude Code in one pass.\n`,
  );
  write('docs/seed-generated.md', `# Seed\n\nContent.\n\n_Generated by some-doc-tool v3_\n`);
  write('docs/seed-boilerplate.md', `# Seed\n\nAs an AI, I cannot verify the residency claim.\n`);

  // The allowance is scoped to one path. The same quotation in a second file is
  // still a violation, which is what keeps the allowance from becoming a rule.
  if (ALLOWED_ENTRY) {
    write(ALLOWED_FILE, `# Legacy\n\nThe worklist states: *"${ALLOWED_ENTRY.quote}."*\n`);
    write('docs/legacy/other-quote.md', `# Elsewhere\n\n*"${ALLOWED_ENTRY.quote}."*\n`);
  }
  // STALE_FILE is deliberately never written, so the allowance that names it has
  // nothing to suppress and check 12 has something real to report.

  // A nested checkout (a linked worktree's `.git` is a FILE, not a directory)
  // and an agent scratch tree. Both carry a real violation, and neither may be
  // scanned: otherwise every "scanned: N" figure this project publishes as
  // evidence depends on who happens to have an agent running, and a check that
  // requires a file to be PRESENT can be satisfied by a copy of some other
  // commit rather than by this tree.
  write('nested-checkout/.git', 'gitdir: /elsewhere/.git/worktrees/nested\n');
  write('nested-checkout/docs/nested.md', '# Nested\n\nAs an AI, I cannot verify this.\n');
  write('.claude/worktrees/agent-x/docs/agent.md', '# Agent\n\nAs an AI, I cannot verify this.\n');

  // Legitimate shapes, all in one file: none of them may raise a problem.
  write(
    'docs/clean.md',
    [
      '# Clean',
      '',
      `**Status:** ACCEPTED ${SEED.middot} **Phase:** 4 ${SEED.middot} Arabic-first ${SEED.emDash} ${SEED.arabic}.`,
      `Bidi marks in a worked example: ${SEED.rlm}${SEED.arabic}${SEED.lrm} renders right to left.`,
      `Mapping: domain objects ${SEED.leftRight} persistence models. State: PROPOSED ${SEED.play} MIGRATED.`,
      `Manual tick sheet: ${SEED.dingbatCheck} accepted, ${SEED.dingbatX} rejected.`,
      'Frequencies include `continuous` (generated by the system as it runs).',
      'A **Type I** report says the controls were suitably designed at a point in time.',
      'The branch is `claude/karar-v2-phase-1-foundation`, merged through PR #6.',
      'Style rule: no AI signatures, no "Generated with ..." lines, no tool attribution.',
      '',
      '```text',
      `Sample terminal output: ${SEED.checkMark} 12 passed`,
      'Generated with some-tool',
      '```',
      '',
      `Inline sample: \`${SEED.checkMark}\` is the codepoint under discussion.`,
      '',
    ].join('\n'),
  );

  return root;
}

// Each case: the check must fail, and one of its problems must match `expect`.
const SELF_TEST_CASES = [
  { check: 'no-emoji', expect: /seed-emoji\.md:5 emoji U\+2705/ },
  { check: 'no-emoji', expect: /seed-emoji-vs16\.md:3 emoji U\+26A0 U\+FE0F/ },
  {
    check: 'no-ai-attribution',
    expect: /seed-attribution\.md:3 AI attribution 'written by Claude Code'/,
  },
  {
    check: 'no-generated-by-line',
    expect: /seed-generated\.md:5 generation attribution 'Generated by some-doc-tool v3'/,
  },
  {
    check: 'no-assistant-boilerplate',
    expect: /seed-boilerplate\.md:3 assistant boilerplate 'As an AI'/,
  },
  {
    check: 'no-assistant-boilerplate',
    expect: /seed-boilerplate\.md:3 assistant boilerplate 'I cannot'/,
  },
  // The allowance is path-scoped: the same quotation elsewhere still fails.
  ...(ALLOWED_ENTRY
    ? [
        {
          check: 'no-assistant-boilerplate',
          expect: /legacy[\\/]other-quote\.md:\d+ assistant boilerplate/,
        },
      ]
    : []),
  // The allowance naming STALE_FILE suppresses nothing here, so it is reported.
  ...(STALE_ENTRY
    ? [
        {
          check: 'style-allowances-live',
          expect: new RegExp(`allowance \\d+ \\(${escapeRe(STALE_FILE)},`),
        },
      ]
    : []),
];

// Negative cases: shapes no rule may flag — the proof the rules are narrow.
const NEGATIVE_SELF_TEST_CASES = [
  { check: 'no-emoji', forbid: /clean\.md/ },
  { check: 'no-ai-attribution', forbid: /clean\.md/ },
  { check: 'no-generated-by-line', forbid: /clean\.md/ },
  { check: 'no-assistant-boilerplate', forbid: /clean\.md/ },
  // The walk stops at the edge of this checkout.
  { check: 'no-assistant-boilerplate', forbid: /nested-checkout/ },
  { check: 'no-assistant-boilerplate', forbid: /(^|[/\\])\.claude[/\\]/ },
  // The allowance does its job on the file it names…
  ...(ALLOWED_ENTRY
    ? [
        { check: 'no-assistant-boilerplate', forbid: new RegExp(escapeRe(ALLOWED_FILE)) },
        // …and having done so, it is not reported as stale.
        {
          check: 'style-allowances-live',
          forbid: new RegExp(`allowance \\d+ \\(${escapeRe(ALLOWED_FILE)},`),
        },
      ]
    : []),
];

function runSelfTest() {
  const fixtureRoot = buildSelfTestFixture();
  const failures = [];
  try {
    const files = walkFiles(fixtureRoot, { exts: MD_EXTS });
    const byName = new Map(runStyleChecks(files, fixtureRoot).checks.map((c) => [c.name, c]));
    for (const { check, expect } of SELF_TEST_CASES) {
      const result = byName.get(check);
      if (!result) {
        failures.push(`${check}: unknown check`);
        continue;
      }
      if (result.problems.length === 0) {
        failures.push(`${check}: did NOT fail on the seeded violation — the check is vacuous`);
        continue;
      }
      if (!result.problems.some((p) => expect.test(p))) {
        failures.push(
          `${check}: failed, but not on the seeded violation (${expect}); got: ${result.problems.join(' | ')}`,
        );
      }
    }
    for (const { check, forbid } of NEGATIVE_SELF_TEST_CASES) {
      const result = byName.get(check);
      if (!result) {
        failures.push(`${check}: unknown check (negative case)`);
        continue;
      }
      const wrong = result.problems.find((p) => forbid.test(p));
      if (wrong) {
        failures.push(
          `${check}: flagged a legitimate shape (${forbid}) — the rule is too broad: ${wrong}`,
        );
      }
    }
  } finally {
    fs.rmSync(fixtureRoot, { recursive: true, force: true });
  }
  return { cases: SELF_TEST_CASES.length + NEGATIVE_SELF_TEST_CASES.length, failures };
}

