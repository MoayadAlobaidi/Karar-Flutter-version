/**
 * Strip the markdown decoration a signature line hides behind — list markers,
 * blockquote markers, emphasis, small-text tags, horizontal-rule dashes — so
 * the anchor sees the sentence itself.
 */
function undecorate(line) {
  return line
    .replace(/<\/?(?:sub|sup|small|em|strong|i|b)>/gi, '')
    .replace(/^[\s>*_~-]+/, '')
    .replace(/[\s*_~]+$/, '')
    .trim();
}

function checkGeneratedByLine(files, root) {
  const problems = [];
  const used = new Set();
  for (const file of files) {
    const relFile = relTo(root, file);
    const lines = stripMarkdownCode(readText(file));
    lines.forEach((raw, i) => {
      const line = undecorate(raw);
      if (line === '') return;
      for (const { label, re } of GENERATED_LINE_RULES) {
        if (!re.test(line)) continue;
        // A line-level rule takes a line-level allowance: the quote must be the
        // whole undecorated line, so an allowance cannot be widened by adding
        // text around the sentence it was written for.
        const allowance = STYLE_ALLOWANCES.find(
          (a) => a.file === relFile && a.check === 'no-generated-by-line' && a.quote === line,
        );
        if (allowance) {
          used.add(STYLE_ALLOWANCES.indexOf(allowance));
          continue;
        }
        problems.push(
          `${relFile}:${i + 1} ${label} '${line}' — a document states what it is, not what produced it`,
        );
      }
    });
  }
  return { problems, usedAllowances: used };
}

function checkAssistantBoilerplate(files, root) {
  return scanProse(
    files,
    root,
    'no-assistant-boilerplate',
    BOILERPLATE_RULES,
    ({ relFile, line, label, text }) =>
      `${relFile}:${line} assistant boilerplate '${text.trim()}' (${label}) — documentation reports in the team's voice; it does not converse`,
  );
}

/**
 * Every allowance must still suppress a real hit. A suppression that no longer
 * suppresses anything has become an unexamined exemption, so it fails here
 * rather than sitting in the list until something new slips under it.
 */
function checkAllowancesLive(usedIndexes) {
  const problems = [];
  STYLE_ALLOWANCES.forEach((a, i) => {
    if (usedIndexes.has(i)) return;
    problems.push(
      `allowance ${i + 1} (${a.file}, ${a.check}, '${a.quote}') matched nothing — delete it, or restore the text it was written for`,
    );
  });
  return problems;
}

/** Run checks 8-11 over one file set and fold their allowance usage together. */
function runStyleChecks(files, root) {
  const emoji = checkEmoji(files, root);
  const attribution = checkAiAttribution(files, root);
  const generated = checkGeneratedByLine(files, root);
  const boilerplate = checkAssistantBoilerplate(files, root);
  const used = new Set([
    ...emoji.usedAllowances,
    ...attribution.usedAllowances,
    ...generated.usedAllowances,
    ...boilerplate.usedAllowances,
  ]);
  return {
    checks: [
      { name: 'no-emoji', problems: emoji.problems },
      { name: 'no-ai-attribution', problems: attribution.problems },
      { name: 'no-generated-by-line', problems: generated.problems },
      { name: 'no-assistant-boilerplate', problems: boilerplate.problems },
      { name: 'style-allowances-live', problems: checkAllowancesLive(used) },
    ],
  };
}

